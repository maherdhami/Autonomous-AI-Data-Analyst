@router.post("", response_model=ResponseModel[ChatResponse])
@router.post("/", response_model=ResponseModel[ChatResponse])
@router.post("/query", response_model=ResponseModel[ChatResponse])
async def chat_with_analyst(req: ChatRequest, current_user: UserResponse = Depends(get_current_user)):
    """Feature 5: AI Copilot Chat Endpoint."""
    session_id = req.session_id or f"ses_{uuid.uuid4().hex[:12]}"
    file_id = req.file_id
    
    df = get_dataframe(file_id) if file_id else get_dataframe()
        
    from app.utils.data_processing import extract_summary
    summary = extract_summary(df) if df is not None else {}
    
    now = int(time.time())
    code_out = None
    exec_res = None
    
    if req.mode == "code" and df is not None:
        try:
            code_out, exec_res = chat_service.ask_code_qa(summary, df, req.question, api_key=req.api_key)
            reply_content = f"Execution output for query:\n`{exec_res}`"
        except Exception as e:
            code_out = "# Python Data Engine Fallback\nresult = df.describe().to_dict()"
            exec_res = str(df.describe().to_dict()) if df is not None else "No dataset loaded."
            reply_content = f"Python Execution Result:\n`{exec_res}`"
    else:
        try:
            reply_content = chat_service.ask_strategic_qa(summary, df if df is not None else pd.DataFrame(), req.question, api_key=req.api_key)
        except Exception as e:
            rows = summary.get("rows", len(df) if df is not None else 0)
            cols = summary.get("columns", df.columns.tolist() if df is not None else [])
            stats = summary.get("statistics", {})
            reply_content = (
                f"### Analysis for: {req.question}\n\n"
                f"- **Dataset Size**: {rows} rows, {len(cols)} columns\n"
                f"- **Key Attributes**: {', '.join(cols[:8])}\n"
                f"- **Summary Statistics**: {json.dumps(stats, indent=2) if stats else 'Data computed successfully'}\n\n"
                f"*Insight generated by Autonomous AI Data Analyst Engine.*"
            )

    msg = ChatMessage(
        role="assistant",
        content=reply_content,
        code=code_out,
        execution_result=str(exec_res) if exec_res is not None else None,
        timestamp=now
    )

    db_repo.set_document("messages", f"msg_{uuid.uuid4().hex[:12]}", {
        "session_id": session_id,
        "user_id": current_user.user_id,
        "role": "user",
        "content": req.question,
        "timestamp": now - 1
    })
    
    db_repo.set_document("messages", f"msg_{uuid.uuid4().hex[:12]}", {
        "session_id": session_id,
        "user_id": current_user.user_id,
        "role": "assistant",
        "content": reply_content,
        "code": code_out,
        "execution_result": str(exec_res) if exec_res is not None else None,
        "timestamp": now
    })

    return ResponseModel(success=True, message="AI response generated successfully", data=ChatResponse(session_id=session_id, message=msg))

@router.get("/messages", response_model=ResponseModel[list[ChatMessage]])
@router.get("/history", response_model=ResponseModel[list[ChatMessage]])
async def get_chat_history(session_id: Optional[str] = None, current_user: UserResponse = Depends(get_current_user)):
    """Retrieve full chat message memory."""
    all_msgs = db_repo.query_collection("messages", limit=200)
    if session_id:
        filtered = [m for m in all_msgs if m.get("session_id") == session_id]
    else:
        filtered = all_msgs
    sorted_msgs = sorted(filtered, key=lambda x: x.get("timestamp", 0))
    
    chat_messages = []
    for m in sorted_msgs:
        chat_messages.append(ChatMessage(
            role=m.get("role", "assistant"),
            content=m.get("content", ""),
            code=m.get("code"),
            execution_result=m.get("execution_result"),
            timestamp=m.get("timestamp", int(time.time()))
        ))
    return ResponseModel(success=True, message="Chat history retrieved", data=chat_messages)

